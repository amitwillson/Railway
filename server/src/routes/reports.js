/**
 * Anyone holding a printed report can scan its QR code and confirm that the
 * document was generated by this system, and that its figures still match.
 */
router.get('/verify/:token', (req, res) => {
  const token = get('SELECT * FROM report_tokens WHERE token = ?', [req.params.token]);
  if (!token) throw notFound('Report');
  const user = token.generated_by ? get('SELECT name, designation FROM users WHERE id = ?', [token.generated_by]) : null;
  const response = {
    verified: true,
    report_type: token.report_type,
    generated_at: token.generated_at,
    generated_by: user ? { name: user.name, designation: user.designation } : null,
  };
  if (token.entity_type === 'inspection') {
    const inspection = get('SELECT * FROM v_inspections i WHERE i.id = ?', [token.entity_id]);
    if (inspection) {
      response.inspection = {
        ref_no: inspection.ref_no,
        type: inspection.inspection_type_name,
        module: inspection.module_name,
        station: inspection.station_name,
        train: inspection.train_number,
        inspector: inspection.inspector_name,
        date: (inspection.started_at ?? inspection.created_at).slice(0, 10),
        status: inspection.status,
        observations: inspection.observation_count,
        open_observations: inspection.open_count,
        closed_observations: inspection.closed_count,
      };
    }
  }
  res.json(response);
});

