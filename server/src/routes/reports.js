/** Shared renderer for the aggregate reports. */
async function respondWithTable(req, res, { title, subtitle, reportType, columns, rows, format = 'json' }) {
  const fileBase = `${reportType}-${stamp()}`;
  if (format === 'json') {
    res.json({ title, subtitle, generated_at: nowIso(), count: rows.length, data: rows });
    return;
  }
  if (format === 'csv') {
    download(res, { fileName: `${fileBase}.csv`, contentType: 'text/csv; charset=utf-8' });
    res.send(toCsv(rows, columns));
    return;
  }
  if (format === 'xlsx') {
    const buffer = await toXlsx([{ name: reportType.slice(0, 28), title, subtitle, columns, rows }]);
    download(res, {
      fileName: `${fileBase}.xlsx`,
      contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    });
    res.send(buffer);
    return;
  }
  const verification = reportToken(req, { reportType, params: req.validQuery });
  const widthSum = columns.length;
  streamPdf(
    res,
    {
      fileName: `${fileBase}.pdf`,
      title,
      subtitle,
      meta: [
        { label: 'Rows', value: rows.length },
        { label: 'Generated by', value: `${req.user.name}${req.user.designation ? `, ${req.user.designation}` : ''}` },
      ],
      verifyUrl: verification.url,
    },
    (doc, helpers) => {
      helpers.table(
        doc,
        columns.map((c) => ({ ...c, width: 1 / widthSum })),
        rows,
        { fontSize: columns.length > 10 ? 6.5 : 8 }
      );
    }
  );
}

